#!/usr/bin/env python3
"""Compile a character definition into the studio family spec and locked palette.

The family spec (contract 1935-k2ib/v1) stays the interface to the Tillandsias
studio, but is generated: edit tool/art/characters/<id>.json, never the output.

Writes tool/art/families/<family>.json and tool/art/palettes/<id>.json. Colours
come from per-part ramps, so every palette entry belongs to exactly one ramp.

Usage: compile_family.py <character id> [--backend <id>]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import colour as C  # noqa: E402
import definitions as D  # noqa: E402
from sync_family import CONTRACT, apply_rig  # noqa: E402

ROOT = D.ROOT
TARGET_FIELDS = ["rect", "anchor", "pixelsPerUnit", "facing", "loop", "durationBeats",
                 "events", "supportFoot", "status", "provenance", "ramps"]
PROFILES = ("moderate", "peak", "overlap", "turn")


def sha_json(o) -> str:
    return hashlib.sha256(json.dumps(o, sort_keys=True, ensure_ascii=False).encode()).hexdigest()


def character_prompt(c: dict) -> str:
    parts = [c["traits"]] + [g["text"] for g in c["garments"] if g.get("text")]
    parts += [p["text"] for p in c.get("props", []) if p.get("text")]
    if c.get("demeanor"):
        parts.append(c["demeanor"])
    return ", ".join(parts)


def workflow_path(backend_id: str, profile: str) -> str:
    per_backend = f"tool/art/workflows/{backend_id}/{profile}.api.json"
    return per_backend if (ROOT / per_backend).exists() else f"tool/art/workflows/character-frame-{profile}.api.json"


def compile_spec(c: dict, style: dict, motion: dict, backend: dict, ramps: dict, palette_path: str) -> dict:
    proxy = {"skin": c["skin"]}
    for g in c["garments"]:
        if "colour" in g:
            proxy.setdefault(g["region"], ramps[g["id"]]["shades"][_base_index(style)])
    proxy["skin"] = ramps["skin"]["shades"][_base_index(style)]
    if c.get("props"):
        proxy["prop"] = ramps[c["props"][0]["id"]]["shades"][_base_index(style)]
    native = {"perRoom": True}
    for t in c["targets"]:
        native[t["room"]] = {"width": t["native"][0], "height": t["native"][1], "pixelScale": t["pixelScale"]}
    frame = {"baselineY": None, "pivot": {"x": None, "y": None, "normalized": False},
             "scale": {"mode": "fixed-per-family", "referencePose": motion["referencePose"], "resolved": None},
             "native": native, **style["frame"]}
    targets = []
    for t in c["targets"]:
        targets.append({"type": "kumbiaManifest", "atlas": t["atlas"],
                        "out": t.get("out", f"assets/art/ensemble/{c['family']}.png"),
                        "manifest": "assets/art/ensemble/manifest.json", "frameId": "{clip}_{drawing}",
                        "fields": TARGET_FIELDS, "packing": {"gutterPx": 2, "trim": True, "anchorRelativeTo": "trimmed-rect"},
                        "requireHumanAcceptance": True, "room": t["room"],
                        "camera": t.get("camera", style["frame"].get("camera", "floor-perspective"))})
    gen = style.get("generation", {})
    spec = {
        "contract": CONTRACT, "pipelineVersion": None, "family": c["family"], "version": 1,
        "project": "kumbia-kombat", "description": c.get("description", ""), "kind": "character-frames",
        "frame": frame, "transparency": style.get("transparency"), "outline": style["outline"],
        "symmetry": style.get("symmetry", "none"), "references": c["references"]["sources"],
        "regions": {}, "reservedRamps": style.get("reservedRamps", []), "palette": {"locked": palette_path},
        "style_prompt": style["prompt"], "style_negative": style["negative"],
        "character_prompt": character_prompt(c), "clips": motion["clips"],
        "generation": {"count_per_pose": gen.get("count_per_pose", 4), "seed_base": c["seedBase"],
                       "seed_policy": gen.get("seed_policy", ""), "backend": "comfyui-api",
                       "workflow": workflow_path(backend["id"], motion["defaultProfile"]),
                       "tiers": {backend.get("tier", "I1"): {"model": backend.get("checkpoint", backend["id"]),
                                                             "steps": backend.get("sampler", {}).get("steps")}},
                       "workflowsByProfile": {p: workflow_path(backend["id"], p) for p in PROFILES},
                       "defaultProfile": motion["defaultProfile"], "profileRules": motion["profileRules"]},
        "qa": style.get("qa", {}), "targets": targets, "adapters": style.get("adapters"),
        "regionsRender": style.get("regionsRender"),
        "$notes": {"spec": f"Generated by tool/art/pipeline/compile_family.py from tool/art/characters/{c['id']}.json. Do not edit by hand.",
                   "character": c["id"], "motionSet": motion["id"]},
        "rigInputs": f"art_runs/inputs/{c['family']}",
        "regionProxyColours": proxy,
    }
    return spec


def _base_index(style: dict) -> int:
    return C.OFFSETS[style["ramp"]["shades"]].index(0)


def palette_doc(c: dict, style: dict, ramps: dict) -> dict:
    colours = [style["outline"].upper()]
    for part in ramps.values():
        colours += part["shades"]
    return {"schema": "tillandsias.palette/v1", "name": c["id"], "colours": colours, "transparent": None,
            "$provenance": {"tool": "tool/art/pipeline/compile_family.py", "definition": f"tool/art/characters/{c['id']}.json",
                            "ramps": {k: v["shades"] for k, v in ramps.items()},
                            "nudged": {k: v["nudged"] for k, v in ramps.items() if v["nudged"]}}}


def compile_character(ident: str, backend_id: str | None = None) -> tuple[dict, dict, dict]:
    return compile_definition(D.load_character(ident), backend_id)


def compile_definition(c: dict, backend_id: str | None = None) -> tuple[dict, dict, dict]:
    if c.get("status") == "rig-only":
        raise D.DefinitionError([f"status: {c['id']} is rig-only and has no family spec yet"])
    style = D.load_style(c["style"])
    motion = D.load_motion(c["motion"]["set"])
    backend = D.resolve_backend(c, style, backend_id)
    ramps = C.build_ramps(c, style)
    palette_path = f"tool/art/palettes/{c['id']}.json"
    spec = compile_spec(c, style, motion, backend, ramps, palette_path)
    return spec, palette_doc(c, style, ramps), motion


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("character")
    ap.add_argument("--backend")
    a = ap.parse_args()
    try:
        spec, palette, motion = compile_character(a.character, a.backend)
    except (D.DefinitionError, C.GateViolation) as e:
        sys.exit(f"refused:{a.character}:{e}")
    n, used, out = write_family(spec, palette, motion)
    print(f"compiled {a.character} -> {out.relative_to(ROOT)}: {n} poses, {used} principles, {len(palette['colours'])} palette colours")


def write_family(spec: dict, palette: dict, motion: dict, families: Path | None = None, palettes: Path | None = None):
    """Fill the spec from the rig and write it with its palette. Returns (poses, principles, spec path)."""
    import os
    os.chdir(ROOT)
    n, used = apply_rig(spec, motion.get("research"))
    palette_out = (palettes / Path(spec["palette"]["locked"]).name) if palettes else ROOT / spec["palette"]["locked"]
    palette_out.write_text(json.dumps(palette, indent=1, ensure_ascii=False) + "\n")
    out = (families or ROOT / "tool" / "art" / "families") / f"{spec['family']}.json"
    out.write_text(json.dumps(spec, indent=1, ensure_ascii=False) + "\n")
    return n, used, out


if __name__ == "__main__":
    main()
